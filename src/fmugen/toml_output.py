"""Render an inferred config dict as a fmugen.toml file."""
import json
import math

#: Variable and settings tables in the order they are written, after ``[model]``.
SECTION_ORDER = ("experiment", "time", "structural_parameters", "parameters", "calculated_parameters",
                 "inputs", "states", "outputs", "locals")
#: Commented example appended to FMI 3 configs: clocks can't be inferred.
CLOCKS_EXAMPLE = """
# FMI 3 clocks run model code on events; they can't be inferred. Example (docs/models.md#clocks-fmi-3):
# [clocks.sample]
# interval = 0.1            # a periodic input clock, ticked by the importer
# call = "sample"           # method (or function) run when it ticks
# [inputs]
# measurement = { start = 0.0, clocks = ["sample"] }   # passed to sample()
"""
#: First lines of every generated fmugen.toml.
HEADER = """\
# fmugen.toml: how this Python model becomes an FMU. Reference: docs/config.md
# Generated by `fmugen init`; check the start values, add units, and remove what you don't need.
"""


def render_toml(data, comments=None):
    """Render an inferred config dict as fmugen.toml text, with comments for the user to review.

    Written by hand rather than with a TOML library so the file can carry comments: per-key notes,
    commented-out examples for constants whose code default isn't an FMI value, and hints per
    section.

    :param data: the config dict (as from :func:`fmugen.interface.infer_config`); must have ``model``.
    :type data: dict
    :param comments: ``(section, key) -> text``. A key of None is a note under the section
        header; a key starting with ``#`` is a hint line; ``("model", "constants.<name>")`` is an
        example value for a commented-out constant.
    :type comments: dict or None
    :return: the file's text.
    :rtype: str
    """
    # one line each: a comment quoting a multi-line exception message would break the TOML (do-mpc)
    comments = {k: " ".join(v.splitlines()) if isinstance(v, str) else v for k, v in (comments or {}).items()}
    lines = [HEADER]
    lines.append("[model]")
    for key, value in data["model"].items():
        if key not in ("constants", "call_constants"):
            lines.append(_with_comment(f"{_key(key)} = {_value(value)}", comments.get(("model", key))))
    if "save_state" not in data["model"] and ("model", "#save_state") in comments:
        lines.append(f"# {comments[('model', '#save_state')]}")
    if "setup" not in data["model"] and ("model", "#setup") in comments:   # training the user gives
        lines.append(f"# {comments[('model', '#setup')]}")
    for note in ("#requirements", "#compile"):
        if ("model", note) in comments:
            lines.append(f"# {comments[('model', note)]}")
    for table in ("constants", "call_constants"):
        real = data["model"].get(table, {})
        examples = [
            (key.split(".", 1)[1], example) for (section, key), example in comments.items()
            if section == "model" and key.startswith(table + ".") and key.split(".", 1)[1] not in real
        ]
        if real or examples:
            lines.append("")
        if examples:
            lines.append("# Arguments whose code default is not an FMI value; the default is used.")
            lines.append("# To override one, uncomment the line" + ("." if real else " and the table header."))
        if real or examples:
            lines.append(f"[model.{table}]" if real else f"# [model.{table}]")
        for name, value in real.items():
            note = comments.get(("constant", f"{table}.{name}"))   # why init wrote it (a default instance)
            lines.append(_with_comment(f"{_key(name)} = {_value(value)}", note or (
                "computed when the FMU initializes" if isinstance(value, dict) and "call" in value else None)))
        for name, example in examples:
            line = f"# {_key(name)} = {_value(example)}" if example else f"# {_key(name)} = ..."
            note = comments.get(("constant", f"{table}.{name}"))   # an argument with no default (a suggestion)
            lines.append(f"{line}  # {note}" if note else line)

    for section in SECTION_ORDER:
        table = data.get(section)
        note = comments.get((section, None))
        hints = [text for (sec, key), text in comments.items() if sec == section and str(key).startswith("#")]
        if not table and not note and not hints:
            continue
        lines.append("")
        lines.append(f"[{section}]")
        if note:
            lines.append(f"# {note}")
        for name, value in (table or {}).items():
            lines.append(_with_comment(f"{_key(name)} = {_value(value)}", comments.get((section, name))))
        lines.extend(f"# {text}" for text in hints)
    if data["model"].get("fmi_version") == 3:
        lines.append(CLOCKS_EXAMPLE.rstrip("\n"))
    return "\n".join(lines) + "\n"


def _with_comment(line, comment):
    """Append an end-of-line comment to a TOML line, when there is one.

    :param line: the TOML line.
    :type line: str
    :param comment: the comment text, or None.
    :type comment: str or None
    :rtype: str
    """
    return f"{line}  # {comment}" if comment else line


def _key(key):
    """A TOML key: bare when it may be, else quoted.

    :param key: the key.
    :type key: str
    :rtype: str
    """
    return key if key.replace("_", "").replace("-", "").isalnum() and key.isascii() else json.dumps(key)


def _value(value):
    """A Python value as TOML text.

    Floats keep their full precision (``repr``) and use TOML's ``nan`` / ``inf``; dicts become
    inline tables.

    :param value: a bool, number, string, list, tuple or dict of these.
    :return: the TOML text.
    :rtype: str
    :raises TypeError: a value TOML can't hold.
    """
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        if math.isnan(value):
            return "nan"
        if math.isinf(value):
            return "inf" if value > 0 else "-inf"
        return repr(value)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_value(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{_key(k)} = {_value(v)}" for k, v in value.items()) + " }" if value else "{}"
    raise TypeError(f"cannot write {value!r} to TOML")
