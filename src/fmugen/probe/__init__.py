"""Probing, output detection and state detection for interface inference.

Split by concern; every name is re-exported here, so ``from fmugen.probe import ...`` keeps working:

- :mod:`fmugen.probe._base`: Shared state of a probe: the setup calls, the time arguments, ``--read`` outputs and constant errors.
- :mod:`fmugen.probe._reading`: Reading results out of what the probe's call returned and the object it changed.
- :mod:`fmugen.probe._from_code`: Outputs and locals read from the model's code (what it returns, the attributes it assigns).
- :mod:`fmugen.probe._arguments`: The arguments a probe call passes: start values, constants, ``*args`` and the step method.
- :mod:`fmugen.probe._calling`: Calling the model in the probe, and retrying with other argument forms when a call fails.
- :mod:`fmugen.probe._checks`: Checks after the probe's step: set-up order, made-up feeds, sizes, tunable attributes, results.
- :mod:`fmugen.probe._classes`: ``--probe`` for a class: construct the object, call the step once, read what changed.
"""
